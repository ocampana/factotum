function t(key, params = {}) {
  const text = MESSAGES[UI_LANG][key] ?? MESSAGES.en[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (_, name) => params[name] ?? "");
}

// Name of a conversation language (ISO code) in the UI language
function languageName(code) {
  try { return new Intl.DisplayNames([UI_LANG], { type: "language" }).of(code); } catch { return code; }
}

// Translate static markup: data-i18n (text), data-i18n-placeholder, data-i18n-title
function translatePage() {
  document.documentElement.lang = UI_LANG;
  document.querySelectorAll("[data-i18n]").forEach((el) => { el.textContent = t(el.dataset.i18n); });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => { el.placeholder = t(el.dataset.i18nPlaceholder); });
  if (document.body.dataset.i18nTitle) document.title = t(document.body.dataset.i18nTitle);
}
